// ---------------------------------------------------------------- timeline

const dist = ([x1, y1], [x2, y2]) => Math.hypot(x2 - x1, y2 - y1);
const packets = []; // { color, frames: [t, x, y][], shows: [t0, t1][] }
const glows = new Map(); // `${box}|${color}` -> [t0, t1][]
const captions = []; // { title, text, t0, t1, n }

let clock = 0;
for (const [n, sc] of SCENARIOS.entries()) {
  const t0 = clock;
  const marks = {};
  let end = t0;
  for (const tr of sc.tracks) {
    let t = tr.at === undefined ? t0 : marks[tr.at];
    if (t === undefined) throw new Error(`unknown mark ${tr.at}`);
    const p = { color: COLOR[tr.color], frames: [], shows: [] };
    for (const s of tr.steps) {
      if (s.mark) marks[s.mark] = t;
      if (s.glow) {
        const key = `${s.glow}|${COLOR[s.color ?? tr.color]}`;
        glows.set(key, [...(glows.get(key) ?? []), [t, t + s.dur]]);
        t += s.dur;
      }
      if (s.move) {
        const start = t;
        s.move.forEach((pt, k) => {
          if (k) t += dist(s.move[k - 1], pt) / s.speed;
          p.frames.push([t, ...pt]);
        });
        p.shows.push([start, t]);
      }
    }
    packets.push(p);
    end = Math.max(end, t);
  }
  clock = end + GAP;
  captions.push({ ...sc, t0, t1: clock, n: n + 1 });
}
const T = clock;

// ---------------------------------------------------------------- SVG

const r = (v) => Math.round(v * 100) / 100;
/** keyTimes must be strictly ascending: nudge ties forward by the smallest step we print. */
function series(points) {
  const out = [];
  for (const [t, v] of points) {
    let k = Math.min(1, Math.max(0, t / T));
    const prev = out.at(-1);
    if (prev && k <= prev[0]) {
      if (v === prev[1]) continue;
      k = prev[0] + 0.00001;
    }
    out.push([k, v]);
  }
  return {
    keyTimes: out.map(([k]) => k.toFixed(5)).join(';'),
    values: out.map(([, v]) => v).join(';'),
  };
}
const clockAttrs = `dur="${r(T)}s" repeatCount="indefinite"`;
function animate(attr, points, calcMode) {
  const { keyTimes, values } = series(points);
  return `<animate attributeName="${attr}" calcMode="${calcMode}" ${clockAttrs} keyTimes="${keyTimes}" values="${values}"/>`;
}
/** Visible exactly inside the given windows (discrete steps). */
const visibility = (windows) => animate('opacity', [[0, 0], ...windows.flatMap(([a, b]) => [[a, 1], [b, 0]])], 'discrete');

const lines = [];
const out = (s) => lines.push(`    ${s}`);

out(START);
out('<style>.anim-static{display:none}@media (prefers-reduced-motion: reduce){.anim{display:none}.anim-static{display:inline}}</style>');
out('<rect x="30" y="1226" width="940" height="44" fill="#201c16" stroke="#3a342a" stroke-width="1.5"/>');
out(
  `<text class="anim-static" x="46" y="1253" font-size="13.5" fill="#cfc8b6" font-family="${MONO}">4 kịch bản: lệnh an toàn · đòn #2 bị Shield 1 chặn · đòn #4 bị Shield 2 chặn · Kill-Switch</text>`,
);
out('<g class="anim">');

// Box glows, under the packets.
for (const [key, windows] of glows) {
  const [box, color] = key.split('|');
  const [x, y, w, h] = BOX[box];
  const pts = [[0, 0], ...windows.flatMap(([a, b]) => [[a, 0], [a + FADE, 1], [b, 1], [b + 2 * FADE, 0]]), [T, 0]];
  const fill = STRONG.has(box) ? 0.3 : 0.12;
  out(
    `  <rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${color}" fill-opacity="${fill}" stroke="${color}" stroke-width="3" opacity="0">${animate('opacity', pts, 'linear')}</rect>`,
  );
}

// Packets: a square on the arrow, hidden while its box glows.
for (const p of packets) {
  const [first, last] = [p.frames[0], p.frames.at(-1)];
  const frames = [[0, first[1], first[2]], ...p.frames, [T, last[1], last[2]]];
  const { keyTimes, values } = series(frames.map(([t, x, y]) => [t, `${x},${y}`]));
  out(
    `  <g opacity="0">${visibility(p.shows)}<animateMotion calcMode="linear" ${clockAttrs} keyTimes="${keyTimes}" values="${values}"/><rect x="-7" y="-7" width="14" height="14" fill="${p.color}" stroke="#17140f" stroke-width="2"/></g>`,
  );
}

// Captions: one per scenario, plus a progress bar that refills each scenario.
for (const c of captions) {
  out(
    `  <g opacity="0">${visibility([[c.t0, c.t1]])}<rect x="46" y="1238" width="40" height="20" fill="#ffd23f"/><text x="66" y="1252.5" text-anchor="middle" font-size="12" font-weight="700" fill="#141414" font-family="${MONO}">${c.n}/${captions.length}</text><text x="100" y="1253" font-size="14"><tspan font-weight="700" fill="#f4efe3">${c.title}</tspan><tspan fill="#cfc8b6" font-family="${MONO}" font-size="13"> · ${c.text}</tspan></text></g>`,
  );
}
const bar = captions.flatMap((c) => [[c.t0, 0], [c.t1 - 0.01, 940], [c.t1, 0]]);
out(`  <rect x="30" y="1268" width="0" height="2" fill="#a39b87">${animate('width', [[0, 0], ...bar, [T, 0]], 'linear')}</rect>`);
out('</g>');
out(END);

const svg = readFileSync(FILE, 'utf8');
const a = svg.indexOf('<!-- anim:start');
const b = svg.indexOf(END);
if (a < 0 || b < 0) throw new Error('anim markers not found in system-pipeline.svg');
const lineStart = svg.lastIndexOf('\n', a) + 1;
writeFileSync(FILE, svg.slice(0, lineStart) + lines.join('\n') + svg.slice(b + END.length));
console.log(`system-pipeline.svg: ${SCENARIOS.length} scenarios, loop ${r(T)}s, ${packets.length} packets, ${glows.size} glows`);
