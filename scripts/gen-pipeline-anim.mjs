#!/usr/bin/env node
/**
 * Writes the animation layer of docs/assets/system-pipeline.svg: packets that run along the arrows, boxes that
 * light up while a packet is inside them, and one caption per scenario. Only the text between the anim markers is
 * replaced; the static diagram around it is edited by hand, and the coordinates below must match it.
 *
 * SMIL only, no script, so it plays inside GitHub's <img>. Every animation shares one clock (begin 0, same dur,
 * repeat forever), so nothing can drift. prefers-reduced-motion hides the layer and shows a static caption instead.
 *
 * Usage: node scripts/gen-pipeline-anim.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const FILE = new URL('../docs/assets/system-pipeline.svg', import.meta.url);
const START = '<!-- anim:start (generated by scripts/gen-pipeline-anim.mjs, do not edit by hand) -->';
const END = '<!-- anim:end -->';

const SPEED = 400; // px per second along an arrow
const GLOW = 0.36; // seconds a box stays lit while the packet is inside
const GAP = 0.8; // seconds of calm between scenarios
const FADE = 0.08;

const COLOR = { green: '#2ee59d', red: '#e6212f', cream: '#e6dec9', white: '#f4efe3' };
const MONO = 'Geist Mono, ui-monospace, SFMono-Regular, Consolas, monospace';

/** [x, y, w, h] of each box, exactly as drawn in the static layer. */
